def _pct_text(value: float) -> str:
    """把 0~100 的百分比畫成字。**一位小數 ＋ 緊接著的 `%`。**

    ⚠️ **格式本身是一條 §1 防線，不是排版偏好。** `summarize_core_satellite` 的
    分子分母都是使用者填的金額，所以**真實組合完全可能剛好算出 62.0 ／ 38.0** ——
    那正是線框拿來示範版面的那一組示意值（實測：`invest_twd` 620000 ／ 380000
    → `core_pct == 62.0`）。
    只要中間夾著 `%` 與抬頭，畫面上就不會出現 `tests/…::_PINNED_FAKE_VALUES`
    釘的那個「數字 ／ 數字」形狀，**真數字不會被誤判成假數字，假數字也不會偷渡成真的**。
    ⛔ 不要「順手」改成 `f"{a} ／ {b}"` —— 那一改，一個**真實**的 62/38 組合會讓
       示意值黑名單轉紅，而修法會變成放寬黑名單。
    """
    return f"{value:.1f}%"


#: 「剛好落在目標上」的容差（**百分點**，不是比率）。
#: ⚠️ 具名而不 inline：`CLAUDE.md §3.3` 反捏造（同一個數字只准定義一次）。
#: 它現在有**兩個**消費者 —— :func:`_render_mix` 的方向詞，與 :func:`_gap_action_text`
#: 的「要不要講金額」；兩者若各寫一個 `0.05`，畫面就可能同時出現
#: 「剛好落在目標上」與「把 NT$xxx 從衛星移到核心」這種自相矛盾的組合。
_ON_TARGET_TOL_PCT: float = 0.05


def _gap_action_text(summary: dict[str, Any]) -> str:
    """差距那一句的**後半**：把「少 8.0%」講成「要搬多少錢」。算不出來就回 `""`。

    ⭐ **為什麼要有這一句（客戶 2026-09-07 逐字）**：「無法判斷這檔基金好不好，
    配息金額，搭配組合以及標的**是否需要調整**」。使用者看到「核心比目標少 8.0%」
    仍然不知道**要動多少錢**；線框 `ia-wireframe.html` 自己也寫著這一格要呈現
    「差距**與所需動作**」，本頁到 2026-09-06 為止只畫了前半。

    算式（三個數全部來自 SSOT `summarize_core_satellite`，本函式**不另開一份計算**）
    -------------------------------------------------------------------------
    ``要往核心搬的金額 = -diff_pct / 100 × total_twd``

    * `diff_pct` ＝ `core_pct − target_pct`（SSOT 定義）。`diff_pct < 0`（核心不足）
      ⇒ 本式為**正** ⇒ 從衛星搬進核心；`diff_pct > 0` ⇒ 為負 ⇒ 從核心搬回衛星。
    * 代數上它等同 ``total_twd × target_pct/100 − core_twd``（把 `core_pct` 展開即得），
      **本函式刻意取前者** —— 因為畫面上那句「少 8.0%」用的就是 `diff_pct`，
      兩句共用同一個數，就**不可能**出現「說少 8%、卻叫你搬一筆對不上的錢」。
    * ⛔ **它是「再平衡」不是「加碼」**：搬的是**已經在組合裡的錢**，`total_twd` 不變。
      所以它**不需要** Form 的「可動用金額」—— 那是**加碼**才需要的輸入。
      （這正是 2026-09-06 那句「本批不畫」的誤判，就地留痕於 :func:`_render_mix`。）

    單位（`CLAUDE.md §4.1`）
    -----------------------
    回傳的金額是 **TWD 投入本金**，與比例的分母同一把尺（SSOT：「分母 = Σ 投入本金」）。
    ⚠️ **不是市值** —— 真的去賣一檔衛星再買核心，成交的是市值。
    這一點**不另外寫在畫面上**，因為 `format_core_satellite_caption()` 就在下一行
    逐字講了「分母 = Σ 投入本金（**金額**加權，非檔數）」；再寫一次就是客戶說的
    「資訊太多、重複」。
    ⚠️ 格式走 :func:`services.format_helpers.fmt_twd`（本頁狀態列與保單表用的同一支）——
    **不另立第二種金額寫法**（`CLAUDE.md §2.1`）。

    三個「不畫」的守則（每一條都是 `CLAUDE.md §1`，不是排版偏好）
    ------------------------------------------------------------
    1. **`is_amount_weighted` 為 False → 回 `""`。** 一檔本金都沒填時分母是 0，
       比例本身就不可信（SSOT docstring 逐字：「False ＝ `core_pct` 不可信」）。
       ⚠️ 今天這條**走不到**（上游 `core_pct` 同時為 `None`，:func:`_render_mix`
       在更前面就 `not_ready()` 了）——**刻意留著**：它是「可以講金額」的**語意**前提，
       哪天上游改成「補一個估計比例」，這條會擋住金額跟著被印出來。
    2. **落在 :data:`_ON_TARGET_TOL_PCT` 內 → 回 `""`。** 那時畫面說的是
       「剛好落在目標上」，再接一句「把 NT$3 搬過去」就是自打嘴巴。
    3. **四捨五入後不足 1 元 → 回 `""`。** 「移 NT$0」是一句沒有意義的指令。

    `n_missing_amount > 0`（**部分**沒填本金）怎麼辦 —— 本批最容易造假的一步
    ----------------------------------------------------------------------
    **決定：照印，但那一句自己要說出它只涵蓋哪幾檔。** 理由三條：

    1. **不能只擋金額不擋比例。** 沒填本金的那幾檔不進分母，**百分比與金額受害程度
       完全一樣**；只把金額藏起來、留著同樣不完整的百分比，是自我矛盾的防線。
    2. **藏起來的代價落在最常見的資料形狀上。** 只要有一檔沒填 `invest_twd`
       就整句消失 —— 而那正是客戶抱怨「看不出要不要調整」的那個情境。
    3. **但金額比百分比更像一道指令**，所以它必須**自己**帶著射程，
       不能靠使用者往下讀 `format_core_satellite_caption()` 那一行才知道。
       ⚠️ 這**不是**重複那一行：那一行講的是「**分母**漏了幾檔」（資料品質），
       這一句講的是「**這個金額**涵蓋幾檔」（指令射程）。同一個事實的兩面，
       但回答的是兩個問題，而只有後者會被拿去下單。

    ⚠️ **一個已知的、與 2026-09-06「62 ／ 38」同型的碰撞風險，就地登記**：
    `tests/test_wf04_portfolio_skeleton.py::_PINNED_FAKE_VALUES` 釘著線框示意值
    ``"200,000"``，而 `fmt_twd(200000)` ＝ ``"NT$200,000"`` **含有那個子字串** ——
    也就是說，一個**真實**的 20 萬再平衡金額會撞上那份示意值黑名單。
    ⚠️ **會由哪一條抓到，本組實測過，寫清楚免得下一個人找錯地方**：
    `test_the_grey_blocks_never_print_the_illustrative_values_from_the_wireframe`
    只掃 `empty` / `missing` / `loaded` **三種 stream**，而金額只在 `priced` 出現 ——
    **它掃不到**。真正會轉紅的是
    `test_a_real_ratio_that_collides_with_the_mock_up_still_passes`（它掃 `priced`）。
    ⛔ **屆時的正解與 62／38 那次完全相同：改 fixture 或改格式，
    絕不是把黑名單放寬。** 目前的 fixture 算出來是 13 萬（預設目標 75%）與
    21 萬（目標 41% 那條），**都沒有碰到**；本段是先把地雷標出來，不是已發生的問題。
    ⚠️ 這個風險**不是本函式引進的**：狀態列的 💰 總投入與保單表的金額欄早就走同一支
    `fmt_twd`，本函式只是多一個站點。
    """
    _diff = summary.get("diff_pct")
    if _diff is None or not summary.get("is_amount_weighted"):
        return ""
    try:
        _diff = float(_diff)
        _total = float(summary.get("total_twd") or 0.0)
    except (TypeError, ValueError):
        # ⛔ 不吞成 0、不猜 —— 算不出來就**什麼都不說**（§1：寧可少講，不可講錯）。
        return ""
    if abs(_diff) < _ON_TARGET_TOL_PCT:
        return ""
    _need_twd = -_diff / 100.0 * _total
    if round(abs(_need_twd)) < 1:
        return ""
    _amount = fmt_twd(abs(_need_twd))
    _move = (f"從衛星移 {_amount} 到核心" if _need_twd > 0
             else f"從核心移 {_amount} 到衛星")
    _missing = int(summary.get("n_missing_amount") or 0)
    _scope = ""
    if _missing:
        _n_priced = int(summary.get("n_funds") or 0) - _missing
        _scope = f"（只算已填本金的 {_n_priced} 檔）"
    return f"{_move}{MIX_MOVE_TAIL}{_scope}"


