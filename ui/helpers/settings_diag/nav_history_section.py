"""「🗄️ NAV 歷史」—— 三個功能一個入口（線框 §03 ⑤ B「合一」）。

客戶拍板的線框：`docs/wireframes/fund-wireframe-final.html` §03「⑤ ⚙️ 設定與診斷」
B · 🗄️ 資料維護 的第一列，原文逐字如下：

> **合一** NAV 歷史 —— **三個功能一個入口**
> **現況**：同一件事分在**兩個分頁**，連名字都不一樣：
> ・管理室「🗄️ NAV 歷史資料管理（CSV 上傳當基底 + 系統增量更新）」
> ・資料診斷「🗂️ NAV 歷史匯入與累積狀態（保單對帳單 CSV → nav_history）」
> **合併後的單一區塊：** ① 上傳對帳單 CSV 當基底　② 🔄 一鍵自動補全缺淨值
> ③ 累積狀態表（哪幾檔補到哪一天）
> **命名採用**「NAV 歷史」，兩個舊標題都不留 —— 留任一個都會讓人以為另一個還在別頁。

⭐ 「合一」合的是**入口**，不是**實作** —— 這一段最重要，先讀完再改這個檔
------------------------------------------------------------------------
動工前實測了三條路徑，**它們的行為不等價**，所以「挑一條留、砍另外兩條」
不是合併，是**刪掉兩個功能**：

| 功能 | 實作 | 代號怎麼來 | 寫到哪 | CSV 形狀 |
|---|---|---|---|---|
| ② 一鍵自動補全 | `nav_history_store.backfill_to_gs` | 持倉 ∪ 選股池，自動 | 本地 cache ＋ 雲端 | 不吃 CSV（連外抓） |
| ① 本地基底 CSV | `nav_history_store.import_nav_csv_multi` | **讀自 CSV 代號欄**，可多檔 | 本地 cache ＋ 雲端 | **必須有代號欄**（代號｜日期｜淨值） |
| ① 對帳單 CSV | `nav_history_gs.import_csv_text` | **使用者手填**，單檔 | **只寫雲端** | 兩欄即可（日期｜淨值），保險公司對帳單就是這個形狀 |

砍掉「對帳單」那條 → 保險公司匯出的兩欄 CSV **無法匯入**（它沒有代號欄）。
砍掉「本地基底」那條 → `cache/nav_history/{code}.json` 這個基底**沒有人寫得進去**，
而健診/長期報酬會優先讀它。**故本模組把三條全部留著，只把它們收到同一個標題底下。**

⚠️ **渲染順序刻意與線框的列舉順序不同（③ 提前到最上面），理由寫在這裡**
--------------------------------------------------------------------------
線框把三件事列成 ①②③，那是**內容清單**不是版面指令。實際渲染時
「③ 累積狀態」必須畫在最前面，因為它答的是「**能不能寫進雲端**」——
燈是 🔴「累積未啟用」時，①② 兩條寫入路徑都只會落在本機、容器重啟就清空。
把它放在動作之後，使用者會先上傳完才發現東西沒存進去
（`CLAUDE.md §1`：不可讓流程「看起來成功」）。
`ui/tab5_data_guard.py` 原碼就地的註解本來就寫著「收起來的話使用者永遠不會知道
歷史淨值根本沒在累積」—— 合一之後這個理由只會更強：它現在是**三個功能共用的前提**。

⚠️ **本模組不含任何取數 / 寫入實作**：三個區塊的本體仍住在原檔
（`ui/tab_manage.py` / `ui/tab5_data_guard.py`），本模組只負責**擺在一起**。
把實作也搬過來會變成「同一份邏輯兩個地方」，正是這一批要消滅的東西。
"""
from __future__ import annotations

import streamlit as st

#: 合一後的區塊標題。**兩個舊標題都不留**（線框原文：留任一個都會讓人以為
#: 另一個還在別頁）。具名成常數，讓守衛可以拿它做 `==` 比對而不是子字串比對。
NAV_HISTORY_HEADING: str = "### 🗄️ NAV 歷史"


def render_nav_history_section() -> None:
    """把 NAV 歷史的三個功能畫在同一個標題底下（⑤ 專用的唯一入口）。

    呼叫端必須先持有 `merge_context.NAV_HISTORY`，否則管理室與資料診斷
    會各自再畫一份自己的舊區塊 —— 那就是這一批要消滅的「兩個入口」。
    """
    from ui.tab5_data_guard import (
        render_nav_accumulation_status,
        render_nav_statement_csv_import,
    )
    from ui.tab_manage import (
        render_nav_backfill_auto_section,
        render_nav_csv_manage_section,
    )

    st.markdown(NAV_HISTORY_HEADING)
    st.caption(
        "基金的歷史淨值**一站集中在這裡**：先看下面這盞燈確認雲端有沒有在累積，"
        "再用「🔄 一鍵自動補全」讓系統自己抓;系統抓不到的（多半是保單平台專屬基金）"
        "才需要你手動上傳 CSV。**以前這三件事分散在兩個分頁、名字還不一樣。**"
    )

    # ③ 累積狀態 —— 一定在最前面（理由見模組 docstring：它是 ①② 的前提）
    render_nav_accumulation_status()

    st.divider()
    # ② 系統自己抓（不需要 CSV）—— 先給最省事的那條
    render_nav_backfill_auto_section()

    st.divider()
    st.caption(
        "── 或 ── **系統抓不到的檔，手動上傳 CSV**。下面兩條路徑吃的 CSV 形狀不同，"
        "**不是重複功能**：對帳單那條只要「日期｜淨值」兩欄、代碼你自己填、只寫雲端;"
        "基底那條要「代號｜日期｜淨值」、可一次多檔、而且會寫進本機 cache 當長期基底。"
    )
    # ① 對帳單 CSV（單檔、代碼手填、只寫雲端）
    render_nav_statement_csv_import()
    # ① 本地基底 CSV（多檔、代號讀自 CSV、寫本機 cache ＋ 雲端）＋ 逐檔增量 / 下載 / 清除
    render_nav_csv_manage_section(
        expander_label="🗄️ 進階：上傳「代號｜日期｜淨值」CSV 當本機基底（多檔）＋ 增量更新 / 備份")
